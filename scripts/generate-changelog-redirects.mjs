#!/usr/bin/env node
// scripts/generate-changelog-redirects.mjs
//
// Generates public/_redirects from the zudo-doc changelog corpus.
//
// Before this script, the file was hand-maintained: its own header told a human to
// "keep this inventory in parity with src/content/docs(-ja)/changelog/zudo-doc/*.mdx",
// so every release had to append two lines by hand. Forgetting was invisible locally
// and failed `changelog-redirects.test.ts` mid-release instead — which is exactly what
// happened during 5.18.2. The inventory is fully derivable, so it is derived.
//
// Contract (asserted by src/__tests__/pages-lib/changelog-redirects.test.ts):
//   one 301 per zudo-doc version, EN block then JA block, each ordered by the same
//   Intl numeric collator the test uses. Sources/destinations are explicit — no
//   globs, no placeholders — because Cloudflare matches these literally.
//
// Runs as part of `pnpm gen:changelog`, so the existing release step maintains it.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const EN_DIR = join(ROOT, "src/content/docs/changelog/zudo-doc");
const JA_DIR = join(ROOT, "src/content/docs-ja/changelog/zudo-doc");
const OUT = join(ROOT, "public/_redirects");

const HEADER = [
  "# Explicit redirects for the pre-package-split zudo-doc changelog routes.",
  "# GENERATED by scripts/generate-changelog-redirects.mjs (runs via `pnpm gen:changelog`).",
  "# Do not edit by hand — it is derived from src/content/docs(-ja)/changelog/zudo-doc/*.mdx.",
];

const collator = new Intl.Collator("en", { numeric: true });

function versions(dir) {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".mdx") && name !== "index.mdx")
    .map((name) => name.slice(0, -".mdx".length))
    .sort(collator.compare);
}

const en = versions(EN_DIR);
const ja = versions(JA_DIR);

// The bilingual corpora must match; a mismatch means a release added one side only.
// Fail loudly rather than emitting a half-correct redirect table.
const enSet = new Set(en);
const jaSet = new Set(ja);
const missing = [
  ...en.filter((v) => !jaSet.has(v)).map((v) => `  JA missing ${v}`),
  ...ja.filter((v) => !enSet.has(v)).map((v) => `  EN missing ${v}`),
];
if (missing.length > 0) {
  console.error("EN/JA zudo-doc changelog corpora differ — cannot generate redirects:");
  console.error(missing.join("\n"));
  process.exit(1);
}

const lines = [
  ...HEADER,
  ...en.map((v) => `/docs/changelog/${v} /docs/changelog/zudo-doc/${v} 301`),
  ...ja.map((v) => `/ja/docs/changelog/${v} /ja/docs/changelog/zudo-doc/${v} 301`),
];
const next = `${lines.join("\n")}\n`;

const previous = readFileSync(OUT, "utf8");
if (previous === next) {
  console.log(`public/_redirects already current (${en.length} versions, ${en.length * 2} rules)`);
} else {
  writeFileSync(OUT, next);
  console.log(`Wrote public/_redirects (${en.length} versions, ${en.length * 2} rules)`);
}
