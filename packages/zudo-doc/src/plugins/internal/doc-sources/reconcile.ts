// Owned-output reconciliation (stage five). A small build-local manifest
// records every output this feature wrote and its content hash. Each run:
//
// 1. validates the complete plan against the manifest and the disk before
//    touching anything — a failure leaves the previous valid output intact;
// 2. writes only changed outputs and removes stale owned outputs that are
//    still byte-identical to what was generated;
// 3. records the new manifest.
//
// Files the manifest does not list are never overwritten or removed, so
// authored content beside generated sections is preserved. An owned file that
// was edited by hand is reported: overwriting it fails the run, and a stale
// edited file is kept and released from ownership.

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { isInside } from "./discover.js";
import type { DocSourcesDiagnostic } from "./model.js";
import type { PlannedOutput } from "./plan.js";

export const MANIFEST_FILE = "manifest.json";
const MANIFEST_VERSION = 1;

interface Manifest {
  version: number;
  /** Project-relative POSIX output roots (one per mount and content/asset dir). */
  roots: string[];
  /** Project-relative POSIX path → sha256 of the generated bytes. */
  files: Record<string, string>;
}

export class DocSourcesReconcileError extends Error {
  constructor(message: string) {
    super(`docSources: ${message}`);
    this.name = "DocSourcesReconcileError";
  }
}

export interface ReconcileOptions {
  projectRoot: string;
  stateDir: string;
  outputs: PlannedOutput[];
  /** Absolute roots planned outputs must stay inside. */
  outputRoots: string[];
}

export interface ReconcileResult {
  written: string[];
  removed: string[];
  unchanged: number;
  diagnostics: DocSourcesDiagnostic[];
}

function hash(content: string | Buffer): string {
  return createHash("sha256").update(content).digest("hex");
}

function toKey(projectRoot: string, abs: string): string {
  return path.relative(projectRoot, abs).split(path.sep).join("/");
}

function readManifest(manifestPath: string): Manifest {
  let raw: string;
  try {
    raw = fs.readFileSync(manifestPath, "utf8");
  } catch {
    return { version: MANIFEST_VERSION, roots: [], files: {} };
  }
  try {
    const parsed = JSON.parse(raw) as Manifest;
    if (parsed.version === MANIFEST_VERSION && Array.isArray(parsed.roots) &&
      parsed.files && typeof parsed.files === "object") {
      return parsed;
    }
  } catch {
    // fall through
  }
  throw new DocSourcesReconcileError(
    `the ownership manifest "${manifestPath}" is unreadable. Remove it together with the generated document-source sections, then rebuild.`,
  );
}

function fileHash(abs: string): string | null {
  try {
    const stat = fs.lstatSync(abs);
    if (!stat.isFile()) return "not-a-file";
    return hash(fs.readFileSync(abs));
  } catch {
    return null;
  }
}

/** The nearest existing ancestor must resolve inside the allowed root. */
function assertContained(abs: string, roots: string[], projectRoot: string): void {
  const lexicalRoot = roots.find((root) => isInside(abs, root) && abs !== root);
  if (lexicalRoot === undefined) {
    throw new DocSourcesReconcileError(`refusing to write "${toKey(projectRoot, abs)}": outside the document-source output roots`);
  }
  let probe = path.dirname(abs);
  while (!fs.existsSync(probe) && probe !== path.dirname(probe)) probe = path.dirname(probe);
  const realProbe = fs.realpathSync.native(probe);
  // Resolve each root through its parent so a root that is itself a symlink
  // to somewhere else does not vouch for its own target.
  const realRoots = roots.map((root) => {
    let r = path.dirname(root);
    while (!fs.existsSync(r) && r !== path.dirname(r)) r = path.dirname(r);
    const real = fs.realpathSync.native(r);
    return path.join(real, path.relative(r, root));
  });
  const inside = realRoots.some((root) => isInside(realProbe, root) || isInside(root, realProbe));
  if (!inside) {
    throw new DocSourcesReconcileError(
      `refusing to write "${toKey(projectRoot, abs)}": its directory resolves outside the output roots through a symlink`,
    );
  }
}

/** Remove now-empty directories upward, never leaving the owned roots. */
function removeEmptyDirs(start: string, roots: string[]): void {
  let dir = start;
  while (roots.some((root) => isInside(dir, root))) {
    try {
      if (fs.readdirSync(dir).length > 0) return;
      fs.rmdirSync(dir);
    } catch {
      return;
    }
    dir = path.dirname(dir);
  }
}

export function reconcile(options: ReconcileOptions): ReconcileResult {
  const { projectRoot, stateDir, outputs, outputRoots } = options;
  const manifestPath = path.join(stateDir, MANIFEST_FILE);
  const manifest = readManifest(manifestPath);
  const diagnostics: DocSourcesDiagnostic[] = [];

  // ---- validate (no mutation) ---------------------------------------------
  const planned = new Map<string, { abs: string; content: string | Buffer; digest: string }>();
  for (const output of outputs) {
    const key = toKey(projectRoot, output.abs);
    if (key.startsWith("..") || path.isAbsolute(key)) {
      throw new DocSourcesReconcileError(`output "${output.abs}" lies outside the project root`);
    }
    assertContained(output.abs, outputRoots, projectRoot);
    planned.set(key, { abs: output.abs, content: output.content, digest: hash(output.content) });
  }

  const toWrite: Array<{ key: string; abs: string; content: string | Buffer; digest: string }> = [];
  let unchanged = 0;
  for (const [key, entry] of planned) {
    const current = fileHash(entry.abs);
    const owned = manifest.files[key];
    if (current === entry.digest) {
      unchanged++;
      continue;
    }
    if (current !== null) {
      if (owned === undefined) {
        throw new DocSourcesReconcileError(
          `"${key}" already exists and was not generated by docSources. Move or remove that file, or choose another mount or "to" path.`,
        );
      }
      if (owned !== current) {
        throw new DocSourcesReconcileError(
          `generated file "${key}" was modified after generation. Edit the source file instead, then remove "${key}" so it can be regenerated.`,
        );
      }
    }
    toWrite.push({ key, ...entry });
  }

  const toRemove: Array<{ key: string; abs: string }> = [];
  for (const [key, digest] of Object.entries(manifest.files)) {
    if (planned.has(key)) continue;
    const abs = path.resolve(projectRoot, ...key.split("/"));
    if (!isInside(abs, projectRoot)) continue;
    const current = fileHash(abs);
    if (current === null) continue;
    if (current !== digest) {
      diagnostics.push({
        level: "warn",
        message: `stale generated file "${key}" was modified after generation; kept and no longer managed`,
      });
      continue;
    }
    toRemove.push({ key, abs });
  }

  // ---- apply --------------------------------------------------------------
  const nextFiles: Record<string, string> = {};
  for (const [key, entry] of planned) nextFiles[key] = entry.digest;
  for (const item of toWrite) {
    fs.mkdirSync(path.dirname(item.abs), { recursive: true });
    fs.writeFileSync(item.abs, item.content);
  }
  const ownedRoots = [
    ...outputRoots,
    ...manifest.roots.map((root) => path.resolve(projectRoot, ...root.split("/"))),
  ];
  for (const item of toRemove) {
    fs.unlinkSync(item.abs);
    removeEmptyDirs(path.dirname(item.abs), ownedRoots);
  }
  // A root whose last owned file was edited and released may still be empty.
  for (const root of ownedRoots) removeEmptyDirs(root, [root]);

  if (Object.keys(nextFiles).length === 0) {
    fs.rmSync(manifestPath, { force: true });
    try {
      fs.rmdirSync(stateDir);
    } catch {
      // keep a non-empty state directory
    }
  } else {
    const sorted = Object.fromEntries(Object.entries(nextFiles).sort(([a], [b]) => a.localeCompare(b)));
    const roots = [...new Set(outputRoots.map((root) => toKey(projectRoot, root)))].sort();
    const serialized = `${JSON.stringify({ version: MANIFEST_VERSION, roots, files: sorted }, null, 2)}\n`;
    let previous = "";
    try {
      previous = fs.readFileSync(manifestPath, "utf8");
    } catch {
      previous = "";
    }
    if (previous !== serialized) {
      fs.mkdirSync(stateDir, { recursive: true });
      const tmp = `${manifestPath}.tmp`;
      fs.writeFileSync(tmp, serialized);
      fs.renameSync(tmp, manifestPath);
    }
  }

  return {
    written: toWrite.map((item) => item.key),
    removed: toRemove.map((item) => item.key),
    unchanged,
    diagnostics,
  };
}

