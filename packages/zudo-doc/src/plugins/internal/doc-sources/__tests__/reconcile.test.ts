import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { exists, listTree, makeProject, read, run, write } from "./helpers.js";

function kb(mount?: string) {
  return {
    sources: [
      {
        id: "kb",
        title: "KB",
        ...(mount === undefined ? {} : { mount }),
        mappings: [
          { id: "m", root: "kb", include: ["**/*.md"], format: "markdown" as const, assets: { include: ["**/*.png"] } },
        ],
      },
    ],
  };
}

describe("owned-output reconciliation", () => {
  it("writes only changes and removes stale outputs on delete, mount change and disable", () => {
    const project = makeProject();
    const docs = path.join(project.root, "src/content/docs");
    write(path.join(project.root, "kb", "a.md"), "# A\n");
    write(path.join(project.root, "kb", "deep", "b.md"), "# B\n");
    write(path.join(project.root, "kb", "pic.png"), Buffer.from([1, 2, 3]));
    const first = run(project, kb());
    expect(first.written.length).toBeGreaterThan(0);

    const second = run(project, kb());
    expect(second.written).toEqual([]);
    expect(second.removed).toEqual([]);

    fs.rmSync(path.join(project.root, "kb", "deep"), { recursive: true });
    const third = run(project, kb());
    expect(third.removed.sort()).toEqual(["src/content/docs/kb/deep/b.mdx", "src/content/docs/kb/deep/index.mdx"]);
    expect(exists(path.join(docs, "kb", "deep"))).toBe(false);

    run(project, kb("renamed"));
    expect(exists(path.join(docs, "kb"))).toBe(false);
    expect(exists(path.join(project.root, "public/doc-sources/kb"))).toBe(false);
    expect(listTree(path.join(docs, "renamed"))).toEqual(["a.mdx", "index.mdx"]);
    expect(exists(path.join(project.root, "public/doc-sources/renamed/pic.png"))).toBe(true);

    const disabled = run(project, { sources: [] });
    expect(disabled.sources).toBe(0);
    expect(listTree(docs)).toEqual([]);
    expect(exists(path.join(project.root, "public/doc-sources"))).toBe(false);
    expect(exists(path.join(project.root, ".zfb/doc-sources"))).toBe(false);
  });

  it("never overwrites authored files and keeps the previous output on failure", () => {
    const project = makeProject();
    const docs = path.join(project.root, "src/content/docs");
    write(path.join(project.root, "kb", "a.md"), "# A\n");
    write(path.join(docs, "kb", "a.mdx"), "---\ntitle: Mine\n---\n\nAuthored.\n");
    expect(() => run(project, kb())).toThrow(/was not generated by docSources/);
    expect(read(path.join(docs, "kb", "a.mdx"))).toContain("Authored.");
    expect(exists(path.join(docs, "kb", "index.mdx"))).toBe(false);

    fs.rmSync(path.join(docs, "kb"), { recursive: true });
    run(project, kb());
    const before = listTree(docs);
    // A collision introduced later fails the run before any mutation.
    write(path.join(project.root, "kb", "A.md"), "# Upper\n");
    write(path.join(project.root, "kb", "b.md"), "# B\n");
    expect(() => run(project, kb())).toThrow(/route collision/);
    expect(listTree(docs)).toEqual(before);
  });

  it("refuses to overwrite a modified owned file and keeps a modified stale file", () => {
    const project = makeProject();
    const docs = path.join(project.root, "src/content/docs");
    write(path.join(project.root, "kb", "a.md"), "# A\n");
    write(path.join(project.root, "kb", "b.md"), "# B\n");
    run(project, kb());

    fs.appendFileSync(path.join(docs, "kb", "a.mdx"), "\nhand edit\n");
    write(path.join(project.root, "kb", "a.md"), "# A changed\n");
    expect(() => run(project, kb())).toThrow(/modified after generation/);

    write(path.join(project.root, "kb", "a.md"), "# A\n");
    fs.writeFileSync(path.join(docs, "kb", "a.mdx"), read(path.join(docs, "kb", "a.mdx")).replace("\nhand edit\n", ""));
    fs.appendFileSync(path.join(docs, "kb", "b.mdx"), "\nkeep me\n");
    fs.rmSync(path.join(project.root, "kb", "b.md"));
    const result = run(project, kb());
    expect(read(path.join(docs, "kb", "b.mdx"))).toContain("keep me");
    expect(result.diagnostics.some((d) => d.level === "warn" && d.message.includes("kb/b.mdx"))).toBe(true);
    // Released: the next run does not report it again.
    expect(run(project, kb()).diagnostics.filter((d) => d.level === "warn")).toEqual([]);
  });

  it("refuses an unreadable manifest instead of guessing ownership", () => {
    const project = makeProject();
    write(path.join(project.root, "kb", "a.md"), "# A\n");
    run(project, kb());
    write(path.join(project.root, ".zfb/doc-sources/manifest.json"), "{ nope");
    expect(() => run(project, kb())).toThrow(/manifest/);
  });

  it("refuses to write through a symlinked output directory that escapes the roots", () => {
    const project = makeProject();
    const outside = path.join(project.root, "..", "elsewhere");
    fs.mkdirSync(outside, { recursive: true });
    fs.symlinkSync(outside, path.join(project.root, "src/content/docs/kb"));
    write(path.join(project.root, "kb", "a.md"), "# A\n");
    expect(() => run(project, kb())).toThrow(/symlink/);
    expect(fs.readdirSync(outside)).toEqual([]);
  });
});

describe("discovery boundaries", () => {
  it("follows symlinks only inside configured roots and survives cycles", () => {
    const project = makeProject();
    const root = path.join(project.root, "kb");
    write(path.join(root, "a.md"), "# A\n");
    write(path.join(project.root, "shared", "s.md"), "# Shared\n");
    write(path.join(project.root, "..", "secret", "x.md"), "# Secret\n");
    fs.symlinkSync(path.join(project.root, "..", "secret"), path.join(root, "secret"));
    fs.symlinkSync(root, path.join(root, "loop"));
    fs.symlinkSync(path.join(project.root, "missing"), path.join(root, "broken.md"));
    const outsideOnly = run(project, kb());
    const warns = outsideOnly.diagnostics.filter((d) => d.level === "warn").map((d) => d.message).join("\n");
    expect(warns).toMatch(/symlink "secret" points outside/);
    expect(warns).toMatch(/cycle at "loop"/);
    expect(warns).toMatch(/broken symlink "broken.md"/);
    expect(listTree(path.join(project.root, "src/content/docs/kb"))).toEqual(["a.mdx", "index.mdx"]);

    // Linking to a directory that is itself a configured root is followed.
    fs.symlinkSync(path.join(project.root, "shared"), path.join(root, "shared"));
    run(project, {
      sources: [
        ...kb().sources,
        {
          id: "shared",
          title: "Shared",
          mappings: [{ id: "s", root: "shared", include: ["*.md"], format: "markdown" as const }],
        },
      ],
    });
    expect(listTree(path.join(project.root, "src/content/docs/kb"))).toContain("shared/s.mdx");
  });

  it("never scans generated output roots, even through an alias", () => {
    const project = makeProject();
    write(path.join(project.root, "kb", "a.md"), "# A\n");
    fs.symlinkSync(path.join(project.root, "src/content/docs"), path.join(project.root, "kb", "docs-alias"));
    run(project, kb());
    expect(listTree(path.join(project.root, "src/content/docs/kb"))).toEqual(["a.mdx", "index.mdx"]);
    // A second run must not pick up its own output.
    run(project, kb());
    expect(listTree(path.join(project.root, "src/content/docs/kb"))).toEqual(["a.mdx", "index.mdx"]);
  });

  it("rejects a mapping root inside the docs directory", () => {
    const project = makeProject();
    write(path.join(project.root, "src/content/docs/inner/a.md"), "# A\n");
    expect(() =>
      run(project, {
        sources: [
          {
            id: "bad",
            title: "Bad",
            mappings: [{ id: "m", root: "src/content/docs/inner", include: ["*.md"], format: "markdown" }],
          },
        ],
      }),
    ).toThrow(/output directory/);
  });
});
