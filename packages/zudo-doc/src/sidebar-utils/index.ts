// ---------------------------------------------------------------------------
// Sidebar item types (mirrors src/config/sidebars.ts)
// ---------------------------------------------------------------------------

export interface SidebarLink {
  type: "link";
  label: string;
  href: string;
}

export interface SidebarDoc {
  type: "doc";
  /** Doc slug, e.g. "getting-started/introduction" */
  id: string;
  /** Override the doc's title in sidebar */
  label?: string;
}

export interface SidebarCategory {
  type: "category";
  label: string;
  items: SidebarItem[];
  collapsed?: boolean;
  sortOrder?: "asc" | "desc";
}

export interface SidebarAutogenerated {
  type: "autogenerated";
  dirName?: string;
}

/**
 * A sidebar item — string shorthand is equivalent to `{ type: "doc", id: slug }`.
 */
export type SidebarItem =
  | SidebarDoc
  | SidebarLink
  | SidebarCategory
  | SidebarAutogenerated
  | string;

/** An explicit editorial tree with an optional local view of a category's children. */
export interface SidebarDefinition {
  items: SidebarItem[];
  /** Resolved occurrence indexes from the forest to a category (not URL segments). */
  initialPath?: number[];
  /** Share across sections using the same editorial tree. Locale/version are added by chrome. */
  contextId?: string;
}

/** Sidebar config keyed by section (categoryMatch value). */
export type SidebarsConfig = {
  [sectionKey: string]: SidebarItem[] | SidebarDefinition | undefined;
};

