it("widens to include the canonical root-index page with an empty slug", () => {
  const { nodes, navigation } = buildSidebarNavigation([], "en", undefined, undefined, {}, () => [leaf(""), ...tree], []);
  const selected = nodes[1]!.occurrenceId!;
  expect(reconcileSidebarScope(navigation, nodes, selected, undefined)).toBe(selected);
  expect(reconcileSidebarScope(navigation, nodes, selected, "")).toBe(SIDEBAR_FOREST_SCOPE);
});


it("stops at a sole canonical root but retains the additional-root forest step", () => {
  const single = buildSidebarNavigation([], "en", undefined, undefined, {}, () => [tree[0]!], []);
  const rootId = single.nodes[0]!.occurrenceId!;
  expect(sidebarScopeNodes(single.navigation, single.nodes, rootId)).toEqual(sidebarScopeNodes(single.navigation, single.nodes, SIDEBAR_FOREST_SCOPE));
  expect(broaderSidebarScope(single.navigation, single.nodes, rootId)).toBeNull();
  const multiple = build();
  expect(broaderSidebarScope(multiple.navigation, multiple.nodes, multiple.nodes[0]!.occurrenceId!)).toBe(SIDEBAR_FOREST_SCOPE);
  expect(sidebarScopeNodes(multiple.navigation, multiple.nodes, SIDEBAR_FOREST_SCOPE)).toHaveLength(2);
});


describe("author disclosure baseline", () => {
  it("inherits the nearest index and permits a leaf override without changing initialPath", () => {
    const docs = [
      { slug: "index", data: { sidebar_initial_expansion: "expanded" } },
      { slug: "utility/index", data: { sidebar_initial_expansion: "collapsed" } },
      { slug: "utility/border", data: { sidebar_initial_expansion: "expanded" } },
    ];
    const data = buildSidebarNavigation(docs, "en", "utility", undefined, {}, () => tree, ["utility"]);
    expect(sidebarInitialExpansion(data.navigation, "utility/background")).toBe("collapsed");
    expect(sidebarInitialExpansion(data.navigation, "utility/border")).toBe("expanded");
    expect(sidebarInitialExpansion(data.navigation, "other/page")).toBe("expanded");
    expect(data.nodes.map((node) => node.slug)).toEqual(["utility"]);
    expect(sidebarInitialExpansion(build().navigation, "utility/background")).toBeUndefined();
  });
  it("honors explicit exceptions and reveals active ancestors", () => {
    expect(sidebarBaselineOpen(tree[1]!, undefined, "utility/background")).toBe(true);
    expect(sidebarBaselineOpen(tree[1]!, "collapsed", "utility/background")).toBe(false);
    expect(sidebarBaselineOpen({ ...tree[1]!, collapsed: false }, "collapsed", "utility/background")).toBe(true);
    expect(sidebarBaselineOpen({ ...tree[1]!, collapsed: true }, "expanded", "utility/background")).toBe(false);
    expect(sidebarBaselineOpen({ ...tree[0]!, collapsed: true }, "collapsed", "utility/background")).toBe(true);
  });
});


describe("initialPathMode node baseline", () => {
  const wind = [leaf("wind", [leaf("wind/utility", [leaf("wind/utility/surfaces", [leaf("wind/utility/surfaces/background"), leaf("wind/utility/surfaces/border")]), leaf("wind/utility/layout")])])];
  const buildWind = (definition: Omit<SidebarDefinition, "items">) => {
    const config: SidebarsConfig = { wind: { items: [{ type: "autogenerated" }], ...definition } };
    return { config, ...buildSidebarNavigation([], "en", "wind", undefined, config, () => wind, ["wind"]) };
  };
  const strip = (nodes: SidebarNavNode[]): SidebarNavNode[] => nodes.map(({ occurrenceId: _id, ...node }) => ({ ...node, children: strip(node.children) }));

  it("keeps the linked section root once, then broadens through each real ancestor", () => {
    const { config, nodes, navigation } = buildWind({ initialPath: [0, 0, 0], initialPathMode: "node" });
    expect(nodes).toHaveLength(1);
    expect(nodes[0]).toMatchObject({ slug: "wind/utility/surfaces", href: "/docs/wind/utility/surfaces", hasPage: true });
    expect(nodes[0]!.children.map((node) => node.slug)).toEqual(["wind/utility/surfaces/background", "wind/utility/surfaces/border"]);
    expect(indexSidebarOccurrences(navigation.roots).get(nodes[0]!.occurrenceId!)).toBe(nodes[0]);
    expect(navigation.roots.map((node) => node.slug)).toEqual(["wind"]);
    expect(navigation.localParentId).toBe(navigation.parents[nodes[0]!.occurrenceId!]);
    const first = broaderSidebarScope(navigation, nodes, null)!;
    expect(sidebarScopeNodes(navigation, nodes, first).map((node) => node.slug)).toEqual(["wind/utility"]);
    const second = broaderSidebarScope(navigation, nodes, first)!;
    expect(sidebarScopeNodes(navigation, nodes, second).map((node) => node.slug)).toEqual(["wind"]);
    expect(broaderSidebarScope(navigation, nodes, second)).toBeNull();
    expect(sidebarScopeNodes(navigation, nodes, nodes[0]!.occurrenceId!)).toEqual(nodes);
    expect(buildSidebarForSection([], "en", "wind", undefined, config, () => wind, ["wind"])).toEqual(strip(nodes));
  });

  it("defaults to children mode and shares the editorial context across modes", () => {
    const children = buildWind({ initialPath: [0, 0, 0] });
    const explicit = buildWind({ initialPath: [0, 0, 0], initialPathMode: "children" });
    const node = buildWind({ initialPath: [0, 0, 0], initialPathMode: "node" });
    expect(children.nodes.map((n) => n.slug)).toEqual(["wind/utility/surfaces/background", "wind/utility/surfaces/border"]);
    expect(explicit.nodes).toEqual(children.nodes);
    expect(children.navigation.localParentId).toBe(node.nodes[0]!.occurrenceId);
    expect(node.navigation.id).toBe(children.navigation.id);
    expect(node.navigation.roots).toEqual(children.navigation.roots);
    expect(node.navigation.parents).toEqual(children.navigation.parents);
  });

  it("keeps the forest for a missing or empty path and accepts a valid leaf target", () => {
    const forest = buildWind({});
    expect(buildWind({ initialPathMode: "node" }).nodes).toEqual(forest.nodes);
    expect(buildWind({ initialPath: [], initialPathMode: "node" }).nodes).toEqual(forest.nodes);
    const leafTarget = buildWind({ initialPath: [0, 0, 0, 1], initialPathMode: "node" });
    expect(leafTarget.nodes.map((node) => node.slug)).toEqual(["wind/utility/surfaces/border"]);
    expect(sidebarScopeNodes(leafTarget.navigation, leafTarget.nodes, broaderSidebarScope(leafTarget.navigation, leafTarget.nodes, null))[0]?.slug).toBe("wind/utility/surfaces");
  });

  it("keeps invalid-index errors in node mode for both builders", () => {
    for (const initialPath of [[1], [-1], [0.5], [0, 0, 0, 0, 0]]) {
      const config: SidebarsConfig = { wind: { items: [{ type: "autogenerated" }], initialPath, initialPathMode: "node" } };
      expect(() => buildSidebarNavigation([], "en", "wind", undefined, config, () => wind, ["wind"])).toThrow("Invalid sidebar initialPath");
      expect(() => buildSidebarForSection([], "en", "wind", undefined, config, () => wind, ["wind"])).toThrow("Invalid sidebar initialPath");
    }
  });

  it("rejects an unknown initialPathMode instead of silently using children mode", () => {
    const config = { wind: { items: [{ type: "autogenerated" }], initialPath: [0], initialPathMode: "self" } } as unknown as SidebarsConfig;
    expect(() => buildSidebarNavigation([], "en", "wind", undefined, config, () => wind, ["wind"])).toThrow("Invalid sidebar initialPathMode");
    expect(() => buildSidebarForSection([], "en", "wind", undefined, config, () => wind, ["wind"])).toThrow("Invalid sidebar initialPathMode");
  });

  it("treats a sole root as terminal and broadens one selected root of several to the forest", () => {
    const sole = buildWind({ initialPath: [0], initialPathMode: "node" });
    expect(sole.nodes.map((node) => node.slug)).toEqual(["wind"]);
    expect(broaderSidebarScope(sole.navigation, sole.nodes, null)).toBeNull();
    const multiple = buildSidebarNavigation([], "en", "utility", undefined, { utility: { items: [{ type: "autogenerated" }], initialPath: [1], initialPathMode: "node" } }, () => tree, ["utility"]);
    expect(multiple.nodes.map((node) => node.slug)).toEqual(["other"]);
    expect(broaderSidebarScope(multiple.navigation, multiple.nodes, null)).toBe(SIDEBAR_FOREST_SCOPE);
  });

  it("selects visible custom/autogenerated nodes without mutating sources", () => {
    const config: SidebarsConfig = { utility: { items: [{ type: "category", label: "Editorial", items: ["other/page", { type: "autogenerated", dirName: "utility" }] }], initialPath: [0, 1], initialPathMode: "node" } };
    const before = JSON.stringify([config, tree]);
    const { nodes, navigation } = build(config);
    expect(JSON.stringify([config, tree])).toBe(before);
    expect(nodes.map((node) => node.slug)).toEqual(["utility/background"]);
    const parent = broaderSidebarScope(navigation, nodes, null)!;
    expect(sidebarScopeNodes(navigation, nodes, parent)[0]?.slug).toBe("utility");
    expect(sidebarScopeNodes(navigation, nodes, broaderSidebarScope(navigation, nodes, parent))[0]?.label).toBe("Editorial");
    expect(buildSidebarForSection([], "en", "utility", undefined, config, () => tree, [])).toEqual(strip(nodes));
  });
});

describe("empty-items object definition fallback", () => {
  const deep = [leaf("wind", [leaf("wind/utility", [leaf("wind/utility/surfaces", [leaf("wind/utility/surfaces/background")])])])];
  const visible = (nodes: SidebarNavNode[]) => nodes.map((node) => node.slug);
  const both = (config: SidebarsConfig, categoryMatch = "wind", source = deep) => ({
    section: buildSidebarForSection([], "en", categoryMatch, undefined, config, () => source, [categoryMatch]),
    navigation: buildSidebarNavigation([], "en", categoryMatch, undefined, config, () => source, [categoryMatch]).nodes,
  });

  it("applies initialPath in every mode identically in both helpers", () => {
    const cases: Array<[SidebarDefinition, string[]]> = [
      [{ items: [], initialPath: [0, 0, 0] }, ["wind/utility/surfaces/background"]],
      [{ items: [], initialPath: [0, 0, 0], initialPathMode: "children" }, ["wind/utility/surfaces/background"]],
      [{ items: [], initialPath: [0, 0, 0], initialPathMode: "node" }, ["wind/utility/surfaces"]],
      [{ items: [], initialPath: [], initialPathMode: "node" }, ["wind"]],
      [{ items: [], initialPathMode: "node" }, ["wind"]],
      [{ items: [] }, ["wind"]],
    ];
    for (const [definition, expected] of cases) {
      const { section, navigation } = both({ wind: definition });
      expect(visible(section)).toEqual(expected);
      expect(visible(navigation)).toEqual(expected);
    }
  });

  it("rejects invalid paths and modes in both helpers", () => {
    for (const initialPath of [[9], [-1], [0.5]]) {
      expect(() => both({ wind: { items: [], initialPath } })).toThrow("Invalid sidebar initialPath");
    }
    const config = { wind: { items: [], initialPath: [0], initialPathMode: "self" } } as unknown as SidebarsConfig;
    expect(() => buildSidebarForSection([], "en", "wind", undefined, config, () => deep, ["wind"])).toThrow("Invalid sidebar initialPathMode");
    expect(() => buildSidebarNavigation([], "en", "wind", undefined, config, () => deep, ["wind"])).toThrow("Invalid sidebar initialPathMode");
  });

  it("keeps category filtering and the missing-config and empty-array fallback unchanged", () => {
    const mixed = [...deep, leaf("other", [leaf("other/page")])];
    const filtered = both({ wind: { items: [], initialPath: [0] } }, "wind", mixed);
    expect(visible(filtered.section)).toEqual(["wind/utility"]);
    expect(visible(filtered.navigation)).toEqual(["wind/utility"]);
    for (const config of [{}, { wind: [] }] as SidebarsConfig[]) {
      const { section, navigation } = both(config, "wind", mixed);
      expect(visible(section)).toEqual(["wind"]);
      expect(visible(navigation)).toEqual(["wind"]);
    }
  });
});

describe("scopeRoot broadening boundary", () => {
  const forest = [leaf("guides", [leaf("guides/page")]), leaf("reference", [leaf("reference/api", [leaf("reference/api/sidebar")])])];
  const buildSection = (section: string, definition?: SidebarDefinition) => buildSidebarNavigation([], "en", section, undefined, definition ? { [section]: definition } : {}, () => forest, ["guides", "reference"]);

  it("rejects an unsupported scopeRoot from both builders", () => {
    const config = { reference: { items: [], scopeRoot: "root" } } as unknown as SidebarsConfig;
    expect(() => buildSidebarNavigation([], "en", "reference", undefined, config, () => forest, ["reference"])).toThrow("Invalid sidebar scopeRoot for reference");
    expect(() => buildSidebarForSection([], "en", "reference", undefined, config, () => forest, ["reference"])).toThrow("Invalid sidebar scopeRoot for reference");
  });

  it("keeps omitted and explicit editorial identity and the full automatic forest", () => {
    const omitted = buildSection("reference");
    const editorial = buildSection("reference", { items: [], scopeRoot: "editorial" });
    expect(editorial.navigation.id).toBe(omitted.navigation.id);
    expect(editorial.navigation.roots.map((node) => node.slug)).toEqual(["guides", "reference"]);
    expect(editorial.nodes.map((node) => node.slug)).toEqual(omitted.nodes.map((node) => node.slug));
    expect(broaderSidebarScope(editorial.navigation, editorial.nodes, null)).toBe(SIDEBAR_FOREST_SCOPE);
    expect(sidebarScopeNodes(editorial.navigation, editorial.nodes, SIDEBAR_FOREST_SCOPE).map((node) => node.slug)).toEqual(["guides", "reference"]);
    expect(buildSection("guides").navigation.id).toBe(omitted.navigation.id);
    const japanese = buildSidebarNavigation([], "ja", "reference", undefined, {}, () => forest, ["guides", "reference"]);
    expect(japanese.navigation.id.startsWith("ja:")).toBe(true);
    expect(japanese.navigation.id).not.toBe(omitted.navigation.id);
  });

  it("caps an empty items section at the category forest and gives sections distinct contexts", () => {
    const configured = buildSection("reference", { items: [], scopeRoot: "configured" });
    const guides = buildSection("guides", { items: [], scopeRoot: "configured" });
    expect(configured.navigation.roots.map((node) => node.slug)).toEqual(["reference"]);
    expect(configured.navigation.parents[configured.navigation.roots[0]!.occurrenceId!]).toBeNull();
    expect(configured.nodes.map((node) => node.slug)).toEqual(["reference"]);
    expect(broaderSidebarScope(configured.navigation, configured.nodes, null)).toBeNull();
    const child = configured.navigation.roots[0]!.children[0]!;
    expect(broaderSidebarScope(configured.navigation, configured.nodes, child.occurrenceId!)).toBe(configured.navigation.roots[0]!.occurrenceId);
    expect(configured.navigation.id).not.toBe(buildSection("reference").navigation.id);
    expect(guides.navigation.id).not.toBe(configured.navigation.id);
    expect(buildSidebarForSection([], "en", "reference", undefined, { reference: { items: [], scopeRoot: "configured" } }, () => forest, ["guides", "reference"]).map((node) => node.slug)).toEqual(["reference"]);
  });

  it("keeps the full forest when configured has no category filter or an autogenerated item without dirName", () => {
    const whole = buildSidebarNavigation([], "en", undefined, undefined, { default: { items: [], scopeRoot: "configured" } }, () => forest, []);
    const editorial = buildSidebarNavigation([], "en", undefined, undefined, {}, () => forest, []);
    expect(whole.navigation.id).toBe(editorial.navigation.id);
    expect(whole.navigation.roots.map((node) => node.slug)).toEqual(["guides", "reference"]);
    const requested = buildSection("reference", { items: [{ type: "autogenerated" }], scopeRoot: "configured" });
    expect(requested.navigation.roots.map((node) => node.slug)).toEqual(["guides", "reference"]);
    expect(requested.navigation.id).toBe(buildSection("reference", { items: [{ type: "autogenerated" }] }).navigation.id);
  });

  it("caps a directory autogeneration without changing the initialPath index space", () => {
    const items = [{ type: "autogenerated" as const, dirName: "reference" }];
    const editorial = buildSection("reference", { items, initialPath: [0], initialPathMode: "node" });
    const configured = buildSection("reference", { items, initialPath: [0], initialPathMode: "node", scopeRoot: "configured" });
    expect(configured.nodes.map((node) => node.slug)).toEqual(["reference/api"]);
    expect(editorial.nodes.map((node) => node.slug)).toEqual(["reference/api"]);
    expect(configured.navigation.roots.map((node) => node.slug)).toEqual(["reference"]);
    expect(configured.navigation.roots[0]!.occurrenceId).toBe(editorial.navigation.roots.find((node) => node.slug === "reference")!.occurrenceId);
    expect(configured.navigation.parents[configured.navigation.roots[0]!.occurrenceId!]).toBeNull();
    expect(configured.navigation.localParentId).toBe(configured.navigation.roots[0]!.occurrenceId);
    const parent = broaderSidebarScope(configured.navigation, configured.nodes, null)!;
    expect(sidebarScopeNodes(configured.navigation, configured.nodes, parent).map((node) => node.slug)).toEqual(["reference"]);
    expect(broaderSidebarScope(configured.navigation, configured.nodes, parent)).toBeNull();
    expect(broaderSidebarScope(editorial.navigation, editorial.nodes, broaderSidebarScope(editorial.navigation, editorial.nodes, null))).toBe(SIDEBAR_FOREST_SCOPE);
    expect(buildSidebarForSection([], "en", "reference", undefined, { reference: { items, initialPath: [0], initialPathMode: "node", scopeRoot: "configured" } }, () => forest, ["reference"]).map((node) => node.slug)).toEqual(["reference/api"]);
  });

  it("caps the ! fallback at the unmatched roots and leaves a curated forest unchanged", () => {
    const fallback = buildSidebarNavigation([], "en", "!", undefined, { "!": { items: [], scopeRoot: "configured" } }, () => forest, ["guides"]);
    expect(fallback.navigation.roots.map((node) => node.slug)).toEqual(["reference"]);
    expect(broaderSidebarScope(fallback.navigation, fallback.nodes, null)).toBeNull();
    const curated = { items: [{ type: "category" as const, label: "Same", items: ["guides/page"] }, { type: "category" as const, label: "Same", items: ["reference/api"] }] };
    const editorial = buildSection("reference", curated);
    const configured = buildSection("reference", { ...curated, scopeRoot: "configured" });
    expect(configured.navigation.id).toBe(editorial.navigation.id);
    expect(configured.navigation.roots.map((node) => node.label)).toEqual(["Same", "Same"]);
    expect(broaderSidebarScope(configured.navigation, configured.nodes, null)).toBeNull();
  });
});
