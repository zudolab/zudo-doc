#!/usr/bin/env node
// Freeze reflection-dependent inline scripts before consumer keepNames/minification.
// Source helpers stay canonical; esbuild emits their closure with keepNames off.
import { buildSync } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export function buildSwitcherScripts() {
  const result = buildSync({
    entryPoints: [resolve(root, "scripts/switcher-script-source.ts")],
    bundle: true, write: false, format: "cjs", platform: "neutral",
    target: "es2020", keepNames: false, minify: false,
    jsx: "automatic", jsxImportSource: "@takazudo/zfb/zudo-react",
    external: ["@takazudo/zfb", "@takazudo/zfb/*"],
  });
  const module = { exports: {} };
  // Only pure helper/constants exports survive tree-shaking; external imports
  // are rejected rather than acquiring consumer/runtime dependencies here.
  new Function("module", "exports", "require", result.outputFiles[0].text)(
    module, module.exports, (name) => { throw new Error(`Unexpected switcher generator import: ${name}`); },
  );
  return Object.fromEntries(Object.entries(module.exports).map(([key, value]) => {
    if (typeof value !== "string") throw new Error(`Expected string ${key}`);
    return [key, value];
  }));
}
export function generateSwitcherScripts() {
  const scripts = buildSwitcherScripts();
  const output = "// GENERATED by scripts/gen-switcher-scripts.mjs; edit helpers or script source.\n" +
    Object.entries(scripts).map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};\n`).join("");
  const path = resolve(root, "src/i18n-version/switcher-generated-scripts.ts");
  if (!existsSync(path) || readFileSync(path, "utf8") !== output) writeFileSync(path, output);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateSwitcherScripts();
