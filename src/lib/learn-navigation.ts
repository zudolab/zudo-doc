import type { DocNavNode } from "@takazudo/zudo-doc/doc-page-props";
import type { SidebarDefinition } from "@takazudo/zudo-doc/sidebar-utils";

/**
 * A linked umbrella row that holds complete native sections. Only the direct
 * branch memberships and their order are authored; everything below a branch
 * comes from the native tree.
 */
export interface UmbrellaNavigation {
  /** Slug of the umbrella landing page, also its header `categoryMatch`. */
  root: string;
  /** Ordered branch slugs, each also its own section's `categoryMatch`. */
  branches: readonly string[];
}

export const learnNavigation: UmbrellaNavigation = {
  root: "learn",
  branches: ["guides", "components", "markdown-features"],
};

/** Header sections that render the umbrella forest. */
export function umbrellaSections(umbrella: UmbrellaNavigation): string[] {
  return [umbrella.root, ...umbrella.branches];
}

/**
 * The one-root umbrella forest: a copy of the native root row whose children
 * are the native branch nodes, descendants included. Branches missing from
 * this locale or version are skipped. Without a linked root page the result
 * is `undefined`, so callers keep the fully native navigation. The input is
 * not mutated.
 */
export function toUmbrellaTree(tree: DocNavNode[], umbrella: UmbrellaNavigation): DocNavNode[] | undefined {
  const bySlug = new Map<string, DocNavNode>();
  const index = (nodes: DocNavNode[]): void => {
    for (const node of nodes) {
      if (!bySlug.has(node.slug)) bySlug.set(node.slug, node);
      index(node.children);
    }
  };
  index(tree);

  const root = bySlug.get(umbrella.root);
  if (!root?.hasPage || !root.href) return undefined;
  const children = umbrella.branches.flatMap((slug) => {
    const branch = bySlug.get(slug);
    return branch ? [branch] : [];
  });
  return [{ ...root, children }];
}

/**
 * Node-mode baseline for one section of an umbrella forest: the root row for
 * the umbrella itself, otherwise the section's actual branch row. Returns
 * `undefined` when the section is not a retained branch.
 */
export function umbrellaSidebar(forest: readonly DocNavNode[], section: string): SidebarDefinition | undefined {
  const root = forest[0];
  if (!root) return undefined;
  const branch = root.children.findIndex((node) => node.slug === section);
  const initialPath = section === root.slug ? [0] : branch >= 0 ? [0, branch] : undefined;
  if (!initialPath) return undefined;
  return {
    items: [{ type: "autogenerated" }],
    initialPath,
    initialPathMode: "node",
    scopeRoot: "configured",
  };
}
